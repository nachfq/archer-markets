// Local integration evidence only. Never uses environment private keys or public networks.
import assert from 'node:assert/strict';
import { createPublicClient, createWalletClient, erc20Abi, http } from 'viem';
import { getMarkets, getPortfolio, getBuyRequest, prepareCreateRequest, prepareAcceptRequest, prepareCancelRequest, prepareExercise, prepareReclaim, optionFactoryAbi } from '@stock-options-lab/sdk';
import { network, readJson, saveJson, mined } from './config.mjs';
import { assertLocalDemo } from './demo-config.mjs';
import { executeOperation, marketFromManifest } from './sdk-operation.mjs';

const chain = network('local'), url = chain.rpcUrls.default.http[0];
const client = createPublicClient({ chain, transport: http(url), cacheTime: 0, pollingInterval: 25 });
const accounts = await client.request({ method: 'eth_accounts' });
assertLocalDemo(url, await client.getChainId(), await client.request({ method: 'web3_clientVersion' }), accounts);
const manifest = await readJson(process.env.DEMO_MANIFEST ?? 'deployments/31337.json');
const record = [manifest, ...(manifest.markets ?? [])].find(m => m.version === 3);
assert(record, 'Deploy a local V3 factory before request checks.');
const market = marketFromManifest({ ...manifest, ...record });
const actor = i => ({ publicClient: client, account: { address: accounts[i], type: 'json-rpc' }, walletClient: createWalletClient({ chain, account: accounts[i], transport: http(url) }) });
const writer = actor(6), buyer = actor(7), competitor = actor(8);
const transactions = [];
const run = async (who, pending) => {
  const operation = await pending;
  const receipt = await executeOperation(who, operation);
  transactions.push({ action: operation.action, hash: receipt.transactionHash, block: receipt.blockNumber });
  return receipt;
};
const count = () => client.readContract({ address: market.factory, abi: optionFactoryAbi, functionName: 'requestCount' });
const balance = (token, address) => client.readContract({ address: token.address, abi: erc20Abi, functionName: 'balanceOf', args: [address] });
const faucetAbi = [{ type: 'function', name: 'faucet', stateMutability: 'nonpayable', inputs: [], outputs: [] }];
for (const who of [writer, buyer, competitor]) for (const token of [market.underlying, market.quote]) await mined(client, await who.walletClient.writeContract({ address: token.address, abi: faucetAbi, functionName: 'faucet' }));
const create = async (optionType, lifetime = 3600n) => {
  const now = (await client.getBlock()).timestamp;
  const terms = { optionType, quantity: 12n * 10n ** 17n, strikeTotal: 312_345678n, premium: 4_567891n, expiry: now + 86400n, acceptUntil: now + lifetime };
  const id = await count();
  await run(buyer, prepareCreateRequest(client, market, buyer.account.address, terms));
  return { id, terms };
};
for (const kind of [0, 1]) {
  const beforeQuote = await Promise.all([writer, buyer].map(w => balance(market.quote, w.account.address)));
  const beforeStock = await Promise.all([writer, buyer].map(w => balance(market.underlying, w.account.address)));
  const {id, terms} = await create(kind);
  let portfolio = await getPortfolio(client, [market], buyer.account.address);
  assert.equal(portfolio.tokens.find(t => t.token.address === market.quote.address).requestPremium, terms.premium);
  assert.equal(portfolio.requests.find(r => r.id === id).state, 0);
  const stale = await prepareAcceptRequest(client, market, competitor.account.address, id);
  await run(writer, prepareAcceptRequest(client, market, writer.account.address, id));
  const request = await getBuyRequest(client, market, id);
  assert.equal(request.state, 1);
  const [snapshot] = await getMarkets(client, [market]);
  const option = snapshot.positions.find(p => p.address.toLowerCase() === request.option.toLowerCase());
  assert.equal(option.buyer.toLowerCase(), buyer.account.address.toLowerCase());
  assert.equal(option.writer.toLowerCase(), writer.account.address.toLowerCase());
  assert.equal(option.underlyingAmount, terms.quantity);
  assert.equal(option.state, 1);
  assert.equal(option.trades[0].price, terms.premium);
  const rejected = await client.waitForTransactionReceipt({ hash: await competitor.walletClient.sendTransaction({ ...stale.request, gas: 4000000n }) });
  assert.equal(rejected.status, 'reverted');
  transactions.push({ action: 'Competing acceptance rejected', hash: rejected.transactionHash, status: rejected.status });
  await assert.rejects(prepareCancelRequest(client, market, buyer.account.address, id), {code: 'UNAVAILABLE'});
  await run(buyer, prepareExercise(client, market, buyer.account.address, request.option));
  const afterQuote = await Promise.all([writer, buyer].map(w => balance(market.quote, w.account.address)));
  const afterStock = await Promise.all([writer, buyer].map(w => balance(market.underlying, w.account.address)));
  assert.equal(afterQuote[0] - beforeQuote[0], terms.premium + (kind === 0 ? terms.strikeTotal : -terms.strikeTotal));
  assert.equal(afterQuote[0] + afterQuote[1], beforeQuote[0] + beforeQuote[1]);
  assert.equal(afterStock[0] + afterStock[1], beforeStock[0] + beforeStock[1]);
  assert.equal(await balance(market.quote, market.factory), 0n);
  assert.equal(await balance(market.underlying, request.option), 0n);
  assert.equal(await balance(market.quote, request.option), 0n);
  console.log(`PASS request ${kind === 0 ? 'call' : 'put'}: premium reservation, whole acceptance, competing acceptance rollback and exercise conservation`);
}
const before = await balance(market.quote, buyer.account.address);
const first = await create(0), second = await create(1, 30n);
await run(buyer, prepareCancelRequest(client, market, buyer.account.address, first.id));
await client.request({ method: 'evm_increaseTime', params: [31] });
await client.request({ method: 'evm_mine', params: [] });
await assert.rejects(prepareAcceptRequest(client, market, writer.account.address, second.id), {code: 'EXPIRED'});
const p = await getPortfolio(client, [market], buyer.account.address);
assert.equal(p.tokens.find(t => t.token.address === market.quote.address).refundablePremium, second.terms.premium);
await run(buyer, prepareCancelRequest(client, market, buyer.account.address, second.id));
assert.equal(await balance(market.quote, buyer.account.address), before);
assert.equal(await balance(market.quote, market.factory), 0n);
console.log('PASS separate requests: cancel and expired refund conserve premium');
const last = await create(1);
await run(writer, prepareAcceptRequest(client, market, writer.account.address, last.id));
const accepted = await getBuyRequest(client, market, last.id);
await client.request({ method: 'evm_setNextBlockTimestamp', params: [Number(last.terms.expiry)] });
await client.request({ method: 'evm_mine', params: [] });
await assert.rejects(prepareExercise(client, market, buyer.account.address, accepted.option), {code: 'EXPIRED'});
await run(writer, prepareReclaim(client, market, writer.account.address, accepted.option));
assert.equal(await balance(market.quote, accepted.option), 0n);
console.log('PASS accepted request: expired option blocks exercise and returns collateral to writer');
await saveJson('deployments/local-requests-smoke.json', { chainId: 31337, rpcUrl: url, factory: market.factory, publicTransactions: false, transactions });
